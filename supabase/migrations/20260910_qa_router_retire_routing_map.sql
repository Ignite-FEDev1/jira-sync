-- ── 왜 뺐나 ────────────────────────────────────────────────────────────────
--
--   제목 앞머리(`[BO_주문관리]`)마다 "지난 6개월 이 메뉴를 누가 제일 많이
--   맡았나"를 세어 판정에 쓰던 표다. 순수 통계라 메뉴가 곧 사람이 아니면
--   틀리는데, **틀려도 "우리 팀" 이라고 자신 있게 답한다.**
--
--   실측 KQ-18742 `[BO_주문관리] 엑셀 다운로드 …`:
--     · 통계  → 박성찬 17/22 (우리 팀)
--     · 사실  → 담당자 이상일 · 에픽 개발처리는 전부 오유연 (둘 다 타팀)
--   통계를 쓰면 남의 팀 건을 우리 팀원에게 배정한다.
--
--   그리고 실제로 쓰이지도 않았다. release_20260914 의 QA 티켓 12건을 돌려
--   보니 판정 경로가 ref_owner 10 · assigned 2 였고 **통계까지 내려간 건이
--   0건**이었다. 이득 없이 오답 위험만 남아 걷어냈다.
--
--   사실이 하나도 안 달린 티켓은 "판정 불가" 로 두는 것이 맞다. 사람이 보면
--   되고, 틀린 이름을 자신 있게 부르는 것보다 낫다.
--
-- ── 왜 drop 하지 않나 ──────────────────────────────────────────────────────
--
--   되돌릴 수 없고, 이 파일이 재적용될 때 남은 데이터를 날린다.
--   지금 0행이라 남겨 두는 비용이 없다. 코드 참조는 모두 제거했으므로
--   아무도 읽고 쓰지 않는다. 정리는 별도 결정으로 남긴다.
--
--   되살리려면: judge 의 티어 순서에서 **사실(Tier 0·3) 뒤**에 두어야 한다.
--   전에는 통계가 앞에 있어서 위 오답이 났다.

comment on table public.qa_router_routing_map is
  '[은퇴 2026-09-10] 프리픽스 통계 기반 담당자 추정. 오답 위험 대비 실사용 0건이라 판정에서 제외. 코드 참조 없음.';

-- 확인: 아무도 안 쓰는 빈 표로 남아 있는지
select (select count(*) from public.qa_router_routing_map) as 남은_행수,
       obj_description('public.qa_router_routing_map'::regclass) as 표시;
