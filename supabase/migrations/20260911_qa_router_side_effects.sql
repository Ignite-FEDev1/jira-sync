-- QA Router · 부수 작업의 실패를 관측 가능하게
-- 실행 위치: scripts/db-migrate.sh (idempotent)
--
-- ── 문제 ────────────────────────────────────────────────────────────────────
--
--   tick 에는 "실패해도 알림은 계속 나가야 하는" 부수 작업이 셋 있다.
--     차수 목록 수집 · 기획티켓 진행 수집 · 판정 결과 확인
--   셋 다 catch 에서 log() 만 하고 넘어간다. log 는 GitHub Actions 콘솔에만
--   남아서, DB·화면·Slack 어디에도 흔적이 없다.
--
--   실측(2026-09-11): 화면이 `09-10 13:26 기준` 에서 멈춰 있었는데,
--   그게 "아직 걷을 때가 아니다"인지 "걷다 실패했다"인지 화면만 봐서는
--   구분할 수 없었다. Actions 로그를 직접 뒤져서야 알았다.
--
-- ── 근본 원인 ───────────────────────────────────────────────────────────────
--
--   catch 하나가 **두 결정을 동시에** 내리고 있었다.
--     1. 흐름 제어 — 던질까 말까   (부수 작업이니 "안 던진다"가 맞다)
--     2. 관측     — 남길까 말까   (남겨야 한다)
--   "안 던진다"를 고르는 순간 "남기지도 않는다"가 딸려 왔다. 두 결정은
--   서로 독립인데 한 곳에 묶여 있었다. 그래서 세 곳이 똑같이 조용하다.
--
-- ── 왜 이벤트 테이블이 아니라 state 한 칸인가 ───────────────────────────────
--
--   tick 은 60초마다 돈다. 실패가 이어지면 분당 한 건씩 쌓여서, 하루면
--   수백 행이 같은 말을 반복한다. 그 표는 "티켓마다 무엇을 했나" 를 담는
--   자리지 "지금 고장났나" 를 담는 자리가 아니다.
--
--   마지막 시도 결과 하나만 덮어쓰면 크기가 안 늘고, 화면은 수집 시각을
--   읽는 바로 그 자리에서 같이 읽을 수 있다.
--
-- ── 담는 모양 ───────────────────────────────────────────────────────────────
--
--   {"plan": {"at": "2026-09-11T02:20:00Z", "error": "Jira 500 …"},
--    "cycles": {"at": "...", "error": null},
--    "outcome": {"at": "...", "error": null}}
--
--   error 가 null 이면 그 시각에 성공했다는 뜻이다. 키를 미리 못 박지 않는다
--   — 부수 작업이 하나 더 늘어도 마이그레이션 없이 담긴다.

alter table public.qa_router_state
  add column if not exists side_effects jsonb not null default '{}'::jsonb;

comment on column public.qa_router_state.side_effects is
  '부수 작업의 마지막 시도 결과. {키: {at, error}}. error=null 이면 성공. '
  '알림을 막지 않는 실패라도 여기에는 반드시 남는다.';

-- 확인: 컬럼이 붙었는지
select column_name, data_type, column_default
  from information_schema.columns
 where table_name = 'qa_router_state'
   and column_name = 'side_effects';
